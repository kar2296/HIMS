router.post('/GetOptions', (req: Request, res: Response, next: NextFunction): any => {
    let promises: Array<any> = [];
    let reqs = req.body as Array<OptionRequest>;
    reqs.forEach(r => {
        let func = OptionBoRegistry[r.Key];
        if (func) {
            let bo = func();
            bo.Request = req;
            if (bo.GetOptions) {
                let p = bo.GetOptions(r.Key, r.Request || { Params: [] })
                    .then((response: any) => {
                        if (r.Default === undefined || r.Default === true) {
                            (<any[]>response[r.Key]).splice(0, 0, { Id: -1, Text: 'Please Select', ReferenceValueCode: -1 });
                        }
                        if (typeof r.Default === 'object') {
                            (<any[]>response[r.Key]).splice(0, 0, r.Default);
                        }
                        return response;
                    });
                promises.push(p);
            } else {
                next(new Error('GetOptions method is not implemented'));
            }
        } else {
            let refBO = BoFactory.GetBo(bo.ReferenceValueBo, req) as any;
            let p = refBO.GetOptions(r.Key, r.Request || { Params: [] })
                .then((response: any) => {
                    if (r.Default === undefined || r.Default === true) {
                        (<any[]>response[r.Key]).splice(0, 0, { Id: -1, Text: 'Please Select', ReferenceValueCode: -1, Color: '' });
                    }
                    if (typeof r.Default === 'object') {
                        (<any[]>response[r.Key]).splice(0, 0, r.Default);
                    }
                    return response;
                });
            promises.push(p);
        }
    });
    Promise.all(promises)
        .then(response => {
            let r = {};
            for (let i of response) {
                for (let j in i) {
                    (<any>r)[j] = (<any>i)[j];
                }
            }
            res.send(r);
        })
        .catch(err => next(err));
});

